def _runtime_config_dir() -> Path:
    if getattr(sys, "frozen", False):
        return Path(sys.executable).resolve().parent
    return Path(__file__).resolve().parent


def _special_phrase_config_candidates() -> list[Path]:
    candidates: list[Path] = []
    env_path = os.environ.get("SPECIAL_PHRASE_TRANSLATIONS_PATH")
    if env_path:
        candidates.append(Path(env_path))
    candidates.append(_runtime_config_dir() / SPECIAL_PHRASE_TRANSLATIONS_FILE)
    candidates.append(Path(__file__).resolve().parent / SPECIAL_PHRASE_TRANSLATIONS_FILE)

    unique: list[Path] = []
    seen: set[str] = set()
    for candidate in candidates:
        key = str(candidate.resolve()) if candidate.is_absolute() else str(candidate)
        if key not in seen:
            unique.append(candidate)
            seen.add(key)
    return unique


def _load_special_phrase_translations() -> dict[str, dict[str, str]]:
    checked = []
    for path in _special_phrase_config_candidates():
        checked.append(str(path))
        if not path.is_file():
            continue
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except Exception as e:
            raise RuntimeError(f"特殊短语配置读取失败：{path}：{e}") from e
        if not isinstance(data, dict):
            raise RuntimeError(f"特殊短语配置格式错误：{path} 根节点必须是 object")

        normalized: dict[str, dict[str, str]] = {}
        for source, targets in data.items():
            if not isinstance(source, str) or not source.strip():
                raise RuntimeError(f"特殊短语配置格式错误：{path} 存在空 source")
            if not isinstance(targets, dict):
                raise RuntimeError(f"特殊短语配置格式错误：{path} -> {source} 必须是 object")
            normalized[source] = {}
            for lang, text in targets.items():
                if not isinstance(lang, str) or not lang.strip():
                    raise RuntimeError(f"特殊短语配置格式错误：{path} -> {source} 存在空语言代码")
                if not isinstance(text, str):
                    raise RuntimeError(
                        f"特殊短语配置格式错误：{path} -> {source}.{lang} 必须是 string"
                    )
                normalized[source][lang] = text
        return normalized

    raise FileNotFoundError(
        "找不到特殊短语配置文件 special_phrase_translations.json，已检查："
        + "；".join(checked)
    )


