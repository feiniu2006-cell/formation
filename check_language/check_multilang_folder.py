def _collect_placeholders(node) -> set:
    if isinstance(node, dict):
        r = set()
        for v in node.values():
            r |= _collect_placeholders(v)
        return r
    if isinstance(node, list):
        r = set()
        for item in node:
            r |= _collect_placeholders(item)
        return r
    if isinstance(node, str):
        return set(PLACEHOLDER_RE.findall(node))
    return set()


def _collect_strings(node) -> list:
    if isinstance(node, dict):
        r = []
        for v in node.values():
            r.extend(_collect_strings(v))
        return r
    if isinstance(node, list):
        r = []
        for item in node:
            r.extend(_collect_strings(item))
        return r
    if isinstance(node, str):
        return [node]
    return []


def _count_translate_strings(node) -> int:
    if isinstance(node, dict):
        return sum(
            _count_translate_strings(v)
            for k, v in node.items()
            if k not in NO_TRANSLATE_KEYS
        )
    if isinstance(node, list):
        return sum(_count_translate_strings(item) for item in node)
    if isinstance(node, str):
        return 1
    return 0


def _progress_log_interval(total: int) -> int:
    if total <= 20:
        return 1
    return max(10, total // 20)


class _TranslationProgress:
    def __init__(self, label: str, total: int):
        self.label = label
        self.total = max(total, 0)
        self.current = 0
        self.interval = _progress_log_interval(self.total)

    def start_attempt(self, attempt: int, max_attempts: int) -> None:
        self.current = 0
        if max_attempts <= 1:
            print(
                f"\n    [翻译进度] {self.label}：开始，共 {self.total} 个文本字段",
                flush=True,
            )
        else:
            print(
                f"\n    [翻译进度] {self.label}：第 {attempt}/{max_attempts} 次，"
                f"共 {self.total} 个文本字段",
                flush=True,
            )

    def step(self, path: str) -> None:
        self.current += 1
        if (
            self.current == 1
            or self.current == self.total
            or self.current % self.interval == 0
        ):
            print(
                f"    [翻译进度] {self.label}：字段 {self.current}/{self.total}"
                f"  {path or '<root>'}",
                flush=True,
            )

    def finish(self) -> None:
        print(
            f"    [翻译进度] {self.label}：完成 {self.current}/{self.total}",
            flush=True,
        )


def _is_translatable(text: str) -> bool:
    cleaned = PLACEHOLDER_RE.sub("", text).strip()
    if len(cleaned) < 4:
        return False
    if re.match(r'^[\d\s\W]+$', cleaned):
        return False
    # 纯数学公式（数字 + 运算符 + x/X 作为乘号），无需翻译
    if re.match(r'^[\d\s×xX+\-=*/%.,()]+$', cleaned):
        return False
    # 移除通用英文术语后若无实质内容，视为不需翻译
    stripped = cleaned
    for term in UNIVERSAL_ENGLISH_TERMS:
        stripped = re.sub(r'\b' + re.escape(term) + r'\b', '', stripped, flags=re.IGNORECASE)
    stripped = stripped.strip()
    if not stripped or len(stripped) < 4 or re.match(r'^[\d\s\W]+$', stripped):
        return False
    return True


def _is_allowed_same_special_phrase(text: str, lang: str | None) -> bool:
    stripped = text.strip()
    if not stripped:
        return False
    if any(stripped.lower() == term.lower() for term in UNIVERSAL_ENGLISH_TERMS):
        return True
    for source, target in _configured_special_terms(lang):
        if stripped.lower() == source.lower() and target == source:
            return True
    return False


def _find_untranslated_paths(src, tgt, lang: str | None = None,
                             path: str = "") -> list[str]:
    if isinstance(src, dict) and isinstance(tgt, dict):
        r = []
        for k in src:
            if k in NO_TRANSLATE_KEYS:
                continue
            if k in tgt:
                child = f"{path}.{k}" if path else k
                r.extend(_find_untranslated_paths(src[k], tgt[k], lang, child))
        return r
    if isinstance(src, list) and isinstance(tgt, list):
        r = []
        for i, (s, t) in enumerate(zip(src, tgt)):
            r.extend(_find_untranslated_paths(s, t, lang, f"{path}[{i}]"))
        return r
    if isinstance(src, str) and isinstance(tgt, str):
        if (
            src == tgt
            and _is_translatable(src)
            and not _is_allowed_same_special_phrase(src, lang)
        ):
            preview = (src[:40] + "...") if len(src) > 40 else src
            return [f"{path}  (\"{preview}\")"]
    return []


def _strip_allowed_english_fragments(text: str, lang: str | None) -> str:
    text = PLACEHOLDER_RE.sub(" ", text)
    # 引号里的 UI 名称/专有词允许保留英文，例如 "Paytable"。
    text = re.sub(r'"[^"]{1,80}"', " ", text)
    for source, target in _configured_special_terms(lang):
        text = _replace_special_source(text, source, " ")
        if target and target != source:
            text = re.sub(re.escape(target), " ", text, flags=re.IGNORECASE)
    for term in UNIVERSAL_ENGLISH_TERMS:
        text = re.sub(r'\b' + re.escape(term) + r'\b', ' ', text, flags=re.IGNORECASE)
    return text


def _english_words(text: str) -> list[str]:
    return [m.group(0).lower() for m in re.finditer(r"[A-Za-z][A-Za-z'-]*", text)]


def _residual_english_fragment(src: str, tgt: str, lang: str | None) -> str | None:
    if lang == SOURCE_LANG:
        return None
    src_words = _english_words(_strip_allowed_english_fragments(src, lang))
    tgt_words = _english_words(_strip_allowed_english_fragments(tgt, lang))
    if len(src_words) < 3 or len(tgt_words) < 3:
        return None

    best: list[str] = []
    for i in range(len(src_words)):
        for j in range(len(tgt_words)):
            k = 0
            while i + k < len(src_words) and j + k < len(tgt_words) and src_words[i + k] == tgt_words[j + k]:
                k += 1
            if k >= 3 and k > len(best):
                candidate = src_words[i:i + k]
                phrase = " ".join(candidate)
                if len(phrase) >= 10 and any(len(word) >= 4 for word in candidate):
                    best = candidate
    return " ".join(best) if best else None


def _find_residual_english_paths(src, tgt, lang: str | None,
                                 path: str = "") -> list[str]:
    if isinstance(src, dict) and isinstance(tgt, dict):
        r = []
        for k in src:
            if k in NO_TRANSLATE_KEYS:
                continue
            if k in tgt:
                child = f"{path}.{k}" if path else k
                r.extend(_find_residual_english_paths(src[k], tgt[k], lang, child))
        return r
    if isinstance(src, list) and isinstance(tgt, list):
        r = []
        for i, (s, t) in enumerate(zip(src, tgt)):
            r.extend(_find_residual_english_paths(s, t, lang, f"{path}[{i}]"))
