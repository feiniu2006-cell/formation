def _atomic_write_json_legacy(path: Path, data) -> None:
    """写入临时文件后重命名，保证目标文件要么完整要么不存在，防止中断产生损坏的 JSON。"""
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(".tmp")
    tmp.write_text(json.dumps(data, ensure_ascii=False, indent=4), encoding="utf-8")
    tmp.replace(path)   # os.replace 在同一文件系统上是原子操作


def _make_file_writable(path: Path) -> None:
    try:
        if path.exists():
            path.chmod(stat.S_IREAD | stat.S_IWRITE)
    except Exception:
        pass


def _atomic_write_json(path: Path, data) -> None:
    """Write JSON through a unique temp file, then atomically replace the target."""
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(f"{path.name}.{os.getpid()}.{threading.get_ident()}.tmp")
    legacy_tmp = path.with_suffix(".tmp")
    tmp.write_text(json.dumps(data, ensure_ascii=False, indent=4), encoding="utf-8")

    last_error: Exception | None = None
    for attempt in range(1, 7):
        try:
            _make_file_writable(path)
            _make_file_writable(tmp)
            tmp.replace(path)
            if legacy_tmp != tmp and legacy_tmp.exists():
                try:
                    legacy_tmp.unlink()
                except Exception:
                    pass
            return
        except PermissionError as e:
            last_error = e
            if attempt < 6:
                time.sleep(0.2 * attempt)
                continue
            break
        except Exception as e:
            last_error = e
            break

    try:
        if tmp.exists():
            tmp.unlink()
    except Exception:
        pass

    raise PermissionError(
        f"写入失败：无法替换 {path}。请确认该 JSON 没有被编辑器/同步工具占用，"
        f"并且文件不是只读。原始错误：{last_error}"
    )


