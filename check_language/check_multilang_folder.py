def _find_first_key_path(node, key_name: str, path: tuple = ()) -> tuple | None:
    if isinstance(node, dict):
        if key_name in node:
            return path + (key_name,)
        for key, value in node.items():
            found = _find_first_key_path(value, key_name, path + (key,))
            if found is not None:
                return found
    if isinstance(node, list):
        for index, item in enumerate(node):
            found = _find_first_key_path(item, key_name, path + (index,))
            if found is not None:
                return found
    return None


def _restore_name_token(node, final_name: str):
    """
    递归替换所有字符串中残留的 NAME_TOKEN。
    使用模糊正则（取 _PH_KEY 前 3 字符作锚点），
    允许 API 在 token 内部增删字符。
    """
    anchor  = re.escape(_PH_KEY[:3])
    # Python 的 \w 会匹配中文，不能用于这里；否则会把 token 后面的
    # “是一款的3”这类正文一起吞掉。
    pattern = anchor + r'[A-Za-z0-9_]*?GAMENAME[A-Za-z0-9_]*?' + anchor + r'[A-Za-z0-9_]*'
    if isinstance(node, dict):
        return {k: _restore_name_token(v, final_name) for k, v in node.items()}
    if isinstance(node, list):
        return [_restore_name_token(item, final_name) for item in node]
    if isinstance(node, str) and re.search(pattern, node, re.IGNORECASE):
        return re.sub(pattern, lambda _: final_name, node, flags=re.IGNORECASE)
    return node


def _needs_language_action(
    lang: str,
    folder_ok: bool,
    json_ok: bool,
    trans_ok,
    mode: str,
    allow_source_fix: bool = False,
) -> bool:
    if lang == SOURCE_LANG:
        return (
            allow_source_fix
            and mode != MODE_FILES
            and _is_db_name_only_issue(trans_ok)
        )
    if lang in MANUAL_TRANSLATION_LANGS:
        return (
            mode != MODE_FILES
            and folder_ok
            and json_ok
            and _has_db_name_issue(trans_ok)
        )
    if mode == MODE_FILES:
        return not (folder_ok and json_ok)
    if mode == MODE_TRANS:
        return folder_ok and json_ok and trans_ok is not True
    return not (folder_ok and json_ok and trans_ok is True)


