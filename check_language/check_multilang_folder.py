def _fix_lang_order(lang_results: list) -> list:
    """修复时固定为 eng -> sch -> 其它语言，确保 sch 可作为第二基准。"""
    indexed = list(enumerate(lang_results))

    def order(item):
        index, lang_result = item
        lang = lang_result[0]
        if lang == SOURCE_LANG:
            return (0, index)
        if lang == SCH_FALLBACK_LANG:
            return (1, index)
        return (2, index)

    return [lang_result for _, lang_result in sorted(indexed, key=order)]


